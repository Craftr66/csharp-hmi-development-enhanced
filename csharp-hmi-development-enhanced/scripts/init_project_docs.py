def main():
    parser = argparse.ArgumentParser(
        description="上位机项目开发文档一键建档",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="示例：python init_project_docs.py \"XX产线上位机\" ./MyProject --customer \"XX公司\""
    )
    parser.add_argument("project", help="项目名称")
    parser.add_argument("output", help="输出目录（项目根目录）")
    parser.add_argument("--customer", default="", help="客户名称")
    parser.add_argument("--force", action="store_true", help="覆盖已存在的文件")
    args = parser.parse_args()

    docs_dir = os.path.join(args.output, "docs")
    os.makedirs(docs_dir, exist_ok=True)

    created, skipped = [], []

    for filename, render in DOCS:
        path = os.path.join(docs_dir, filename)
        if os.path.exists(path) and not args.force:
            skipped.append(filename)
            continue

        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(render(args.project, args.customer))
        created.append(filename)

    print(f"项目：{args.project}")
    print(f"目录：{os.path.abspath(docs_dir)}")
    print()

    if created:
        print(f"[OK] 已创建 {len(created)} 份文档：")
        for f in created:
            print(f"     + {f}")

    if skipped:
        print()
        print(f"[SKIP] {len(skipped)} 份文档已存在（未覆盖，如需覆盖加 --force）：")
        for f in skipped:
            print(f"     - {f}")

    print()
    print("提示：")
    print("  1. 先填写 00-软件需求规格说明书.md，把'待确认事项'问清楚")
    print("  2. 每轮对话后追加 05-开发进度日志.md")
    print("  3. 协议细节填入 02-接口与通信协议说明书.md 并与下位机方签字确认")
    return 0


